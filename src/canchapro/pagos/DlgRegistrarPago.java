    /**
     * Abre el diálogo y devuelve el pago registrado, o vacío si se canceló.
     */
    public static Optional<Pago> registrar(Window parent, ReservaServicio servicio, Reserva reserva, Usuario usuario,
            String nombreNegocio) {
        DlgRegistrarPago dialogo = new DlgRegistrarPago(parent, servicio, reserva, usuario, nombreNegocio);
        dialogo.setVisible(true);
        return Optional.ofNullable(dialogo.pagoRegistrado);
    }

    private void registrar() {
        try {
            BigDecimal monto = Validador.monto(txtMonto.getText(), "El monto");
            pagoRegistrado = servicio.registrarPago(reserva.getCodigo(), monto,
                    (MetodoPago) cboMetodo.getSelectedItem(), txtObservacion.getText(), usuario);
            Reserva actualizada = servicio.obtener(reserva.getCodigo());
            Object[] opciones = {"Ver comprobante", "Cerrar"};
            int opcion = JOptionPane.showOptionDialog(this, "Pago " + pagoRegistrado.getCodigo() + " registrado por "
                    + FormatoMoneda.formatear(pagoRegistrado.getMonto()) + ".\n"
                    + "Saldo pendiente: " + FormatoMoneda.formatear(actualizada.getSaldo()) + "\n"
                    + "Estado de la reserva: " + actualizada.getEstado(),
                    getTitle(), JOptionPane.DEFAULT_OPTION, JOptionPane.INFORMATION_MESSAGE, null, opciones, opciones[0]);
            dispose();
            if (opcion == 0) {
                DlgComprobante.mostrar(getOwner(), FormatoPago.comprobante(pagoRegistrado, actualizada, nombreNegocio));
            }
        } catch (CanchaProException e) {
            JOptionPane.showMessageDialog(this, e.getMessage(), getTitle(), JOptionPane.WARNING_MESSAGE);
        }
    }

