    private void ingresar() {
        char[] password = txtPassword.getPassword();
        try {
            Sesion sesion = contexto.getLoginServicio().autenticar(txtUsuario.getText(), new String(password));

            if (sesion.getUsuario().isDebeCambiarPassword()) {
                DlgCambiarPassword dialogo = new DlgCambiarPassword(this,
                        contexto.getLoginServicio(), sesion.getUsuario(), true);
                dialogo.setVisible(true);
                if (!dialogo.isPasswordCambiada()) {
                    txtPassword.setText("");
                    return;
                }
            }

            new FrmPrincipal(contexto, sesion).setVisible(true);
            dispose();
        } catch (CanchaProException e) {
            JOptionPane.showMessageDialog(this, e.getMessage(), "Iniciar sesión", JOptionPane.WARNING_MESSAGE);
            txtPassword.setText("");
            txtPassword.requestFocusInWindow();
        } finally {
            Arrays.fill(password, '\0');
        }
    }

