    // POO - Reutilización / Relaciones: el diálogo TIENE un PnlClientes; reutiliza la misma pantalla de clientes.
    private final PnlClientes pnlClientes;
    private Cliente seleccionado;

    public DlgBuscarCliente(Window parent, ClienteServicio servicio) {
        super(parent);
        initComponents();

        pnlClientes = new PnlClientes(servicio);
        pnlClientes.activarModoSeleccion();
        pnlClientes.setAlHacerDobleClic(this::aceptar);
        getContentPane().add(pnlClientes, BorderLayout.CENTER);

        setSize(1050, 600);
        setLocationRelativeTo(parent);
        pnlClientes.enfocarBusqueda();
    }

    /**
     * Abre el diálogo y espera a que el usuario elija un cliente.
     *
     * @return el cliente elegido, o vacío si canceló
     */
    public static Optional<Cliente> seleccionar(Window parent, ClienteServicio servicio) {
        DlgBuscarCliente dialogo = new DlgBuscarCliente(parent, servicio);
        dialogo.setVisible(true);
        return Optional.ofNullable(dialogo.seleccionado);
    }

    private void aceptar(Cliente cliente) {
        seleccionado = cliente;
        dispose();
    }

