    public PnlServicios(ServicioAdicionalServicio servicio) {
        this.servicio = servicio;
        initComponents();

        cboTipoCobro.setModel(new DefaultComboBoxModel<>(TipoCobro.values()));
        tblServicios.setModel(modeloTabla);
        tblServicios.setAutoCreateRowSorter(true);
        tblServicios.setSelectionMode(ListSelectionModel.SINGLE_SELECTION);
        tblServicios.getSelectionModel().addListSelectionListener(e -> {
            if (!e.getValueIsAdjusting()) {
                seleccionarFila();
            }
        });

        cargarTabla();
        limpiarFormulario();
    }

    private void cargarTabla() {
        modeloTabla.setServicios(servicio.listar());
    }

    private void seleccionarFila() {
        int fila = tblServicios.getSelectedRow();
        if (fila >= 0) {
            mostrarServicio(modeloTabla.getServicio(tblServicios.convertRowIndexToModel(fila)));
        }
    }

    private void mostrarServicio(ServicioAdicional s) {
        codigoSeleccionado = s.getCodigo();
        lblCodigoValor.setText(s.getCodigo());
        txtNombre.setText(s.getNombre());
        txtDescripcion.setText(s.getDescripcion());
        txtPrecio.setText(s.getPrecio().toPlainString());
        cboTipoCobro.setSelectedItem(s.getTipoCobro());
        lblEstadoValor.setText(s.isActivo() ? "Activo" : "Inactivo");
        btnActivarDesactivar.setText(s.isActivo() ? "Desactivar" : "Activar");
        btnActivarDesactivar.setEnabled(true);
    }

    private void limpiarFormulario() {
        codigoSeleccionado = null;
        tblServicios.clearSelection();
        lblCodigoValor.setText("(nuevo)");
        txtNombre.setText("");
        txtDescripcion.setText("");
        txtPrecio.setText("");
        cboTipoCobro.setSelectedItem(TipoCobro.POR_RESERVA);
        lblEstadoValor.setText("-");
        btnActivarDesactivar.setText("Desactivar");
        btnActivarDesactivar.setEnabled(false);
        txtNombre.requestFocusInWindow();
    }

    private void guardar() {
        try {
            BigDecimal precio = Validador.monto(txtPrecio.getText(), "El precio");
            TipoCobro tipo = (TipoCobro) cboTipoCobro.getSelectedItem();
            ServicioAdicional s = codigoSeleccionado == null
                    ? servicio.registrar(txtNombre.getText(), txtDescripcion.getText(), precio, tipo)
                    : servicio.actualizar(codigoSeleccionado, txtNombre.getText(), txtDescripcion.getText(), precio, tipo);
            JOptionPane.showMessageDialog(this, "Servicio " + s.getCodigo() + " guardado.",
                    "Servicios adicionales", JOptionPane.INFORMATION_MESSAGE);
            recargarYSeleccionar(s.getCodigo());
        } catch (CanchaProException e) {
            mostrarAdvertencia(e.getMessage());
        }
    }

    private void activarDesactivar() {
        if (codigoSeleccionado == null) {
            return;
        }
        try {
            ServicioAdicional s = servicio.obtener(codigoSeleccionado);
            servicio.cambiarEstado(codigoSeleccionado, !s.isActivo());
            recargarYSeleccionar(codigoSeleccionado);
        } catch (CanchaProException e) {
            mostrarAdvertencia(e.getMessage());
        }
    }

    private void recargarYSeleccionar(String codigo) {
        cargarTabla();
        int filaModelo = modeloTabla.indiceDe(codigo);
        if (filaModelo >= 0) {
            int filaVista = tblServicios.convertRowIndexToView(filaModelo);
            tblServicios.setRowSelectionInterval(filaVista, filaVista);
        }
    }

    private void mostrarAdvertencia(String mensaje) {
        JOptionPane.showMessageDialog(this, mensaje, "Servicios adicionales", JOptionPane.WARNING_MESSAGE);
    }

