    private void guardar() {
        try {
            servicio.guardar(txtNombreNegocio.getText(), chkModuloTienda.isSelected(), (Integer) spnAnticipo.getValue());
            JOptionPane.showMessageDialog(this, "Configuración guardada. Los cambios ya están aplicados.",
                    "Configuración", JOptionPane.INFORMATION_MESSAGE);
        } catch (CanchaProException e) {
            JOptionPane.showMessageDialog(this, e.getMessage(), "Configuración", JOptionPane.WARNING_MESSAGE);
        }
    }

    private void recargar() {
        int opcion = JOptionPane.showConfirmDialog(this,
                "Se volverán a leer todos los archivos de la carpeta de datos.\n"
                + "Úselo después de copiar datos de prueba o de corregir un archivo.\n¿Desea continuar?",
                "Recargar archivos", JOptionPane.YES_NO_OPTION);
        if (opcion != JOptionPane.YES_OPTION) {
            return;
        }
        // La ventana se obtiene antes: al recargar, la pantalla principal vuelve a crear este panel.
        Window ventana = SwingUtilities.getWindowAncestor(this);
        try {
            RegistroErroresCarga registro = servicio.recargarArchivos();
            JOptionPane.showMessageDialog(ventana, resumen(registro), "Recargar archivos",
                    registro.hayErrores() ? JOptionPane.WARNING_MESSAGE : JOptionPane.INFORMATION_MESSAGE);
        } catch (CanchaProException e) {
            JOptionPane.showMessageDialog(ventana, e.getMessage(), "Recargar archivos", JOptionPane.ERROR_MESSAGE);
        }
    }

    private static String resumen(RegistroErroresCarga registro) {
        if (!registro.hayErrores()) {
            return "Archivos recargados correctamente, sin errores.";
        }
        List<ErrorCarga> errores = registro.getErrores();
        StringBuilder sb = new StringBuilder("Archivos recargados. Se omitieron ")
                .append(errores.size()).append(" registro(s) con errores:\n\n");
        errores.stream().limit(MAX_ERRORES_MOSTRADOS).forEach(e -> sb.append("• ").append(e).append('\n'));
        if (errores.size() > MAX_ERRORES_MOSTRADOS) {
            sb.append("… y ").append(errores.size() - MAX_ERRORES_MOSTRADOS).append(" más (ver bitácora).\n");
        }
        if (!registro.getRespaldos().isEmpty()) {
            sb.append("\nCopia de los archivos originales en: ").append(String.join(", ", registro.getRespaldos()));
        }
        return sb.toString();
    }

    private void abrirCarpeta() {
        try {
            Desktop.getDesktop().open(servicio.getCarpetaDatos().toFile());
        } catch (IOException | UnsupportedOperationException | IllegalArgumentException e) {
            JOptionPane.showMessageDialog(this, "No se pudo abrir la carpeta: " + e.getMessage(),
                    "Configuración", JOptionPane.WARNING_MESSAGE);
        }
    }

    private void mostrarBitacora() {
        try {
            txtBitacora.setText(servicio.leerBitacora());
            txtBitacora.setCaretPosition(txtBitacora.getDocument().getLength());
        } catch (CanchaProException e) {
            txtBitacora.setText(e.getMessage());
        }
    }

